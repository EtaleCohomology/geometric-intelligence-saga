"""06 見逃しと空振り：合図の基準をどこに置くか（本編第6章）。

合図のもとになる点数（境界までの近さが縮む速さなど）を、架空の分布で作る。
  何も起きない時期      ：点数は 平均 0、標準偏差 1 の正規分布
  危うい出来事が起きる時期：点数は 平均 2、標準偏差 1 の正規分布
  危うい時期の割合（事前の確率）：p = 0.02（めったに起きない）
1. 基準 c を動かしたときの、見逃しの割合と空振りの割合（同じ点数のままでは、両方を同時には減らせない）
2. 見逃し１回の重さを、空振り何回分（k）とするかを一族が決めると、期待される損失を最も小さくする基準が計算で出る
   点数の分布が上のとおりなら、見逃しの重さ k、空振りの重さ 1 のとき、
   「危うい時期である確率」が 1/(1+k) を超えたら合図を出す、という基準が最もよい（ベイズの決定の規則）
3. 段階ごとに別の基準を置く（軽い備えは早めに、重い備えは慎重に）
"""
import numpy as np
from scipy.stats import norm

mu0, mu1, p = 0.0, 2.0, 0.02

def miss(c):   return norm.cdf(c, mu1, 1)           # 危うい時期なのに、点数が c 未満
def false(c):  return norm.sf(c, mu0, 1)            # 何も起きない時期なのに、点数が c 以上

print("1. 基準 c と、見逃し・空振りの割合")
print("   c     見逃しの割合  空振りの割合  合図が鳴ったときに本当に危うい割合")
for c in [0.5, 1.0, 1.5, 2.0, 2.5, 3.0]:
    tp = p * (1 - miss(c)); fp = (1 - p) * false(c)
    print(f"   {c:.1f}   {miss(c):.3f}        {false(c):.3f}        {tp / (tp + fp):.3f}")
print("   めったに起きない出来事では、基準を低くすると、鳴った合図の大半が空振りになる。")

def post(s):
    a = p * norm.pdf(s, mu1, 1); b = (1 - p) * norm.pdf(s, mu0, 1)
    return a / (a + b)

def best_c(k):
    """見逃しの重さ k、空振りの重さ 1 のとき、期待される損失 k·p·見逃し + (1−p)·空振り を最小にする c。"""
    cs = np.linspace(-3, 6, 90001)
    loss = k * p * miss(cs) + (1 - p) * false(cs)
    return cs[np.argmin(loss)]

print("\n2. 見逃し１回の重さ k（空振り何回分か）と、最もよい基準")
for k in [1, 10, 30, 100, 300]:
    c = best_c(k)
    # 理論の答え：事後の確率が 1/(1+k) になる点数
    c_theory = (np.log((1 - p) / (p * k)) + (mu1**2 - mu0**2) / 2) / (mu1 - mu0)
    print(f"   k = {k:3d}  最もよい c = {c:.3f}（式から {c_theory:.3f}）  その点数での危うい確率 {post(c):.4f}（1/(1+k) = {1 / (1 + k):.4f}）"
          f"  見逃し {miss(c):.3f}  空振り {false(c):.3f}")
print("   k を決めるのは数学ではなく、一族の価値である。k が決まれば、基準は計算で出る。")

print("\n3. 段階ごとの基準（それぞれの段階に、別の k を置く。値は架空）")
stages = [("身の回りを確かめる", 300), ("書類を整える", 100), ("資産の一部を動かす", 10)]
for name, k in stages:
    c = best_c(k)
    print(f"   {name:10s}  k = {k:3d}  基準 c = {c:.2f}  見逃し {miss(c):.3f}  空振り {false(c):.3f}  1年（12回）あたりの空振りの回数の見込み {12 * (1 - p) * false(c):.2f}")
print("   人が移るかどうかは、合図ではなく、一族が決める（本編第6章）。")
