"""06 選ばれた事実の偏りの検定（第3章・第7章）。

物語の第7章の表の数字（架空）を使う。母集団は、選ばれた事実を見る前に決めておく。
  事実の全体（母集団）     1,412件  不利な事実 33％（466件）
  比べる相手のアカウント    640件   不利な事実 61％
  12のアカウント           118件   不利な事実 108件（92％）
1. 2人の分け方の一致（コーエンのカッパ）を先に確かめる
2. 12のアカウントが、比べる相手と同じ選び方をしていたとしたら、ここまで偏る確率（二項分布の上側の確率）
3. アカウントを1つずつ除いて、同じ計算をやり直す（互いに広め合っていた分、独立とみなす計算は証拠を大きく見すぎる）
"""
import numpy as np
from scipy.stats import binom

rng = np.random.default_rng(2)

# ---- 1. 2人の分け方の一致（架空の分類結果） ---------------------------
n = 1412
true = rng.choice(3, size=n, p=[0.33, 0.47, 0.20])      # 0 不利、1 中立、2 有利
def rater(t, err):
    flip = rng.random(n) < err
    return np.where(flip, rng.choice(3, size=n), t)
kaito, yuki = rater(true, 0.08), rater(true, 0.08)
po = np.mean(kaito == yuki)
pe = sum(np.mean(kaito == k) * np.mean(yuki == k) for k in range(3))
kappa = (po - pe) / (1 - pe)
print(f"2人の一致の割合 {po:.3f}、コーエンのカッパ {kappa:.3f}（0.8 を超えれば、十分に高いとされることが多い）")

# ---- 2. 二項分布の上側の確率 -----------------------------------------
k, m = 108, 118
for name, p0 in [("事実の全体（33％）", 0.33), ("比べる相手のアカウント（61％）", 0.61)]:
    print(f"{name:22s}と同じ選び方なら、118件中108件以上が不利になる確率: {binom.sf(k - 1, m, p0):.2e}")

# ---- 3. アカウントを1つずつ除く ---------------------------------------
# 12のアカウントごとの、引用した事実の数と、そのうち不利な事実の数（架空。合計 118 と 108）
per_total = np.array([18, 15, 13, 12, 11, 10, 9, 8, 7, 6, 5, 4])
per_unfav = np.array([17, 14, 12, 11, 10, 9, 8, 7, 7, 6, 4, 3])
assert per_total.sum() == 118 and per_unfav.sum() == 108
print("\nアカウントを1つずつ除いた場合（比べる相手の 61％ と比べる）")
for i in range(12):
    mt, kt = per_total.sum() - per_total[i], per_unfav.sum() - per_unfav[i]
    print(f"  {i+1:2d}番目を除く：{kt:3d}/{mt:3d} = {kt/mt:.0%}  上側の確率 {binom.sf(kt - 1, mt, 0.61):.1e}")

# ---- 4. 条項の線に関わる数字の割合 -----------------------------------
print("\n条項の線に関わる数字の割合：全体 18％、比べる相手 22％、12のアカウント 64％")
print("12のアカウントが118件中76件（64％）以上を選ぶ確率（比べる相手の 22％ と同じ選び方なら）:",
      f"{binom.sf(75, 118, 0.22):.1e}")
print("\n注意：この検定が示すのは『選び方が偏っていた』ことまでで、アカウントの持ち主が誰かは示さない。")
